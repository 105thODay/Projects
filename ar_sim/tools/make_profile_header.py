#!/usr/bin/env python3
"""Generate profile_vectors.hpp from Networked_AR_Simulation_Profile.json.

The oracle vectors and retained limits are copied from the package by this script,
never retyped, so the simulator is checked against the profile as delivered.
Usage: python tools/make_profile_header.py <profile.json> > profile_vectors.hpp
"""
import json
import sys

d = json.load(open(sys.argv[1]))
t, b, w, q, s = d["timing_allocations"], d["bandwidth"], d["default_workload"], d["model_modes"]["transport_queue"], d["scoring"]
rf, f0 = d["model_modes"]["integrated_rf_display"], [c for c in d["cases"] if c["id"] == "F0"][0]["parameters"]
out = []
out.append("#ifndef PROFILE_VECTORS_HPP")
out.append("#define PROFILE_VECTORS_HPP")
out.append("")
out.append("// GENERATED by tools/make_profile_header.py from %s version %s (%s)." % (d["profile_id"], d["version"], d["date"]))
out.append("// Do not edit by hand: regenerate when the profile changes.")
out.append("")
out.append("#include <cstdint>")
out.append("")
out.append("struct TimingVector")
out.append("{")
out.append("   const char* mCase;                                // vector name in the profile")
out.append("   int         mOpportunitiesHz;                     // urgent opportunity rate")
out.append("   int         mErasedBeforeSuccess;                 // failed attempts before the qualifying copy")
out.append("   int         mInputMs;                             // I allowance")
out.append("   int         mDeliveryMs;                          // D allowance")
out.append("   int         mDisplayMs;                           // P allowance")
out.append("   int         mUncertaintyMs;                       // U allowance")
out.append("   double      mLatencyUpperMs;                      // expected upper bound")
out.append("   bool        mExpectedPass;                        // expected verdict against the 100 ms limit")
out.append("};")
out.append("")
out.append("struct BoundaryVector")
out.append("{")
out.append("   int64_t mElapsedUs;                               // t_photon - t_input, or -1 for null")
out.append("   int64_t mUncertaintyUs;                           // added uncertainty")
out.append("   bool    mCorrect;                                 // effect correct")
out.append("   int     mApplyCount;                              // times the operation was applied")
out.append("   bool    mExpectedPass;                            // expected response verdict")
out.append("};")
out.append("")
out.append("namespace Profile")
out.append("{")
def c(name, value, note):
    out.append("   const int64_t %-34s = %d;%s// %s" % (name, value, " " * max(1, 14 - len(str(value))), note))
c("cDEADLINE_US", d["retained_limits"]["remote_input_to_correct_photon_ms"] * 1000, "NET-001")
c("cLIMIT_BITS", b["max_charged_bits_per_window"], "NET-002")
c("cWINDOW_US", b["window_us"], "NET-002 rolling window")
c("cINPUT_READY_US", t["input_ready_max_us"], "NET-007 (I)")
c("cOPPORTUNITY_MILLIHZ", t["urgent_period_us"]["denominator"] * 1000 * 1000000 // t["urgent_period_us"]["numerator"], "NET-008")
c("cDELIVERY_US", t["successful_attempt_to_publication_max_us"], "NET-009 (D)")
c("cDISPLAY_US", t["publication_to_photon_max_us"], "NET-010 (P)")
c("cUNCERTAINTY_US", t["added_measurement_uncertainty_max_us"], "NET-011 (U)")
c("cPUBLICATION_BOUND_US", s["network_only_necessary_publication_bound_us"], "ready to publication, networking only")
c("cURGENT_COPIES", t["urgent_total_copies"], "copies per urgent event")
c("cBOUNDED_ERASURES", t["bounded_erased_copies_before_success"], "NET-012")
al = b["allocations_bps"]
c("cSHARE_STATE_BITS", al["routine_state_and_cooperative_navigation"], "starting reservation")
c("cSHARE_URGENT_BITS", al["urgent_events_and_repeats"], "starting reservation")
c("cSHARE_CONTROL_BITS", al["control_and_receipts"], "starting reservation")
c("cSHARE_REPAIR_BITS", al["background_repair"], "starting reservation")
c("cSHARE_HEADROOM_BITS", al["uncommitted_headroom"], "starting reservation")
c("cPHY_BPS", q["default_phy_bps"], "illustrative PHY, not measured")
c("cENCODE_US", q["encode_us"], "illustrative")
c("cDECODE_US", q["decode_and_publish_us"], "illustrative")
c("cPROPAGATION_US", q["propagation_us"], "illustrative")
c("cNODES", w["participant_count"], "starter workload")
c("cDURATION_S", w["duration_s"], "")
c("cWARMUP_S", w["warmup_s"], "")
c("cDRAIN_S", w["drain_s"], "")
c("cINPUT_MILLIHZ", int(round(w["input_rate_per_node_hz"] * 1000)), "")
c("cSTATE_MILLIHZ", int(round(w["state_packets_per_node_hz"] * 1000)), "")
c("cSTATE_BITS", w["state_packet_charged_bits"], "abstract complete-frame cost")
c("cURGENT_BITS", w["urgent_copy_charged_bits"], "abstract complete-frame cost")
c("cCONTROL_MILLIHZ", int(round(w["control_packets_per_node_hz"] * 1000)), "")
c("cCONTROL_BITS", w["control_packet_charged_bits"], "")
c("cREPAIR_MILLIHZ", int(round(w["repair_packets_per_node_hz"] * 1000)), "")
c("cREPAIR_BITS", w["repair_packet_charged_bits"], "")
r = d["resource_defaults"]
c("cURGENT_EVENT_CAP", r["urgent_events_per_node"], "NET-015")
c("cURGENT_BYTE_CAP", r["urgent_bytes_per_node"], "NET-015")
c("cDEDUP_ENTRIES", r["dedup_event_entries_per_node"], "NET-013")
c("cDEDUP_RETENTION_MS", r["dedup_retention_ms"], "NET-013")
c("cMAX_DATAGRAM_BYTES", r["max_wire_datagram_bytes"], "before modeled link overhead")
c("cVIDEO_BITS_PER_EYE_FRAME", rf["study_coded_bits_per_eye_frame"], "F0: inherited study")
c("cVIDEO_BURST_BPS", rf["study_video_burst_bps_per_eye"], "F0: inherited study")
c("cVIDEO_MILLIHZ", rf["video_period_us"]["denominator"] * 1000 * 1000000 // rf["video_period_us"]["numerator"], "F0")
c("cRANGING_NODES", f0["reference_nodes"], "F0")
c("cRANGING_PAIRS", f0["reference_pairs"], "F0")
c("cRANGING_PAIR_HZ", f0["pair_rate_hz"], "F0")
c("cRANGING_OCCUPANCY_US", int(round(f0["ranging_occupancy_per_superframe_ms"] * 1000)), "F0: per superframe")
out.append("")
out.append("   const TimingVector cTIMING_VECTORS[] =")
out.append("   {")
for v in d["analytical_vectors"]:
    out.append('      { "%s", %d, %d, %d, %d, %d, %d, %.17g, %s },' % (v["case"], v["opportunities_hz"], v["erased_attempts_before_success"],
               v["input_ms"], v["successful_D_ms"], v["display_ms"], v["uncertainty_ms"], v["latency_upper_ms"], "true" if v["expected_response_pass"] else "false"))
out.append("   };")
out.append("   const int cTIMING_VECTOR_COUNT = %d;" % len(d["analytical_vectors"]))
out.append("")
out.append("   const BoundaryVector cBOUNDARY_VECTORS[] =")
out.append("   {")
for v in s["boundary_vectors"]:
    out.append("      { %d, %d, %s, %d, %s }," % (-1 if v["elapsed_us"] is None else v["elapsed_us"], v["uncertainty_us"],
               "true" if v["correct"] else "false", v["apply_count"], "true" if v["response_pass"] else "false"))
out.append("   };")
out.append("   const int cBOUNDARY_VECTOR_COUNT = %d;" % len(s["boundary_vectors"]))
out.append("}")
out.append("")
out.append("#endif")
print("\n".join(out))
